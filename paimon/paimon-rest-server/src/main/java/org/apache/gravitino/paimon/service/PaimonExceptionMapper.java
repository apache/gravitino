package org.apache.gravitino.paimon.service;

import javax.ws.rs.WebApplicationException;
import javax.ws.rs.core.MediaType;
import javax.ws.rs.core.Response;
import javax.ws.rs.ext.ExceptionMapper;
import javax.ws.rs.ext.Provider;
import org.apache.gravitino.paimon.common.PaimonCatalogException;
import org.apache.paimon.rest.RESTApi;
import org.apache.paimon.rest.exceptions.AlreadyExistsException;
import org.apache.paimon.rest.exceptions.BadRequestException;
import org.apache.paimon.rest.exceptions.ForbiddenException;
import org.apache.paimon.rest.exceptions.NoSuchResourceException;
import org.apache.paimon.rest.exceptions.NotAuthorizedException;
import org.apache.paimon.rest.exceptions.NotImplementedException;
import org.apache.paimon.rest.exceptions.ServiceUnavailableException;
import org.apache.paimon.rest.responses.ErrorResponse;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Maps exceptions thrown by the Paimon REST resources to HTTP responses in the format Paimon's
 * RESTCatalog client expects: an {@link ErrorResponse} JSON body whose {@code code} drives the
 * client-side exception (see {@code org.apache.paimon.rest.DefaultErrorHandler}).
 *
 * <p>Response bodies are serialized with Paimon's shaded Jackson object mapper because Paimon's DTO
 * annotations live in a relocated package that Jersey's unshaded Jackson feature cannot see.
 */
@Provider
public class PaimonExceptionMapper implements ExceptionMapper<Exception> {

  private static final Logger LOG = LoggerFactory.getLogger(PaimonExceptionMapper.class);

  @Override
  public Response toResponse(Exception exception) {
    ErrorResponse errorResponse = toErrorResponse(exception);
    int statusCode = errorResponse.getCode();
    if (statusCode >= 500) {
      LOG.error("Paimon REST server error: {}", exception.getMessage(), exception);
    }
    return Response.status(statusCode)
        .entity(toJson(errorResponse))
        .type(MediaType.APPLICATION_JSON_TYPE)
        .build();
  }

  private ErrorResponse toErrorResponse(Exception exception) {
    if (exception instanceof PaimonCatalogException) {
      return toCatalogError((PaimonCatalogException) exception);
    } else if (exception instanceof NoSuchResourceException) {
      NoSuchResourceException e = (NoSuchResourceException) exception;
      return new ErrorResponse(e.resourceType(), e.resourceName(), e.getMessage(), 404);
    } else if (exception instanceof AlreadyExistsException) {
      AlreadyExistsException e = (AlreadyExistsException) exception;
      return new ErrorResponse(e.resourceType(), e.resourceName(), e.getMessage(), 409);
    } else if (exception instanceof NotAuthorizedException) {
      return error(exception, 401);
    } else if (exception instanceof ForbiddenException) {
      return error(exception, 403);
    } else if (exception instanceof NotImplementedException
        || exception instanceof UnsupportedOperationException) {
      return error(exception, 501);
    } else if (exception instanceof ServiceUnavailableException) {
      return error(exception, 503);
    } else if (exception instanceof BadRequestException) {
      return error(exception, 400);
    } else if (exception instanceof IllegalArgumentException) {
      return error(exception, 400);
    } else if (exception instanceof WebApplicationException) {
      // Errors generated by the framework itself (unknown path, bad method, bad query
      // parameter): keep the original status and render the Paimon error body.
      WebApplicationException e = (WebApplicationException) exception;
      return new ErrorResponse(null, null, e.getMessage(), e.getResponse().getStatus());
    } else {
      return new ErrorResponse(
          null,
          null,
          "Server error: " + (exception.getMessage() == null ? "" : exception.getMessage()),
          500);
    }
  }

  private ErrorResponse error(Exception exception, int statusCode) {
    return new ErrorResponse(null, null, exception.getMessage(), statusCode);
  }

  private ErrorResponse toCatalogError(PaimonCatalogException exception) {
    switch (exception.reason()) {
      case NOT_FOUND:
      case ALREADY_EXISTS:
        return new ErrorResponse(
            exception.resource() == null ? null : exception.resource().name(),
            exception.resourceName(),
            exception.getMessage(),
            exception.reason() == PaimonCatalogException.Reason.NOT_FOUND ? 404 : 409);
      case INVALID:
        return error(exception, 400);
      case UNSUPPORTED:
        return error(exception, 501);
      case FAILURE:
      default:
        return error(exception, 500);
    }
  }

  private String toJson(ErrorResponse errorResponse) {
    try {
      return RESTApi.OBJECT_MAPPER.writeValueAsString(errorResponse);
    } catch (Exception e) {
      LOG.warn("Failed to serialize error response, falling back to plain message", e);
      return String.format("{\"message\":\"%s\",\"code\":%d}", errorResponse.getMessage(), 500);
    }
  }
}
